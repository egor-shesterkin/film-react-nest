SELECT
  (session_item ->> 'id')::uuid,
  (film ->> 'id')::uuid,
  NULLIF(session_item ->> 'daytime', '')::timestamptz,
  session_item ->> 'hall',
  NULLIF(session_item ->> 'rows', '')::integer,
  NULLIF(session_item ->> 'seats', '')::integer,
  NULLIF(session_item ->> 'price', '')::integer,
  COALESCE(
    ARRAY(SELECT jsonb_array_elements_text(session_item -> 'taken')),
    ARRAY[]::text[]
  )
FROM source,
  jsonb_array_elements(payload) AS film,
  jsonb_array_elements(film -> 'schedule') AS session_item;
